#!/usr/bin/env python3
"""Rasterize TTF fonts into 4-bit anti-aliased bitmap fonts for the 3DS UI.
Usage: mkfont.py out.c  (fonts: DejaVu, Bitstream Vera license - see FONTS-LICENSE)"""
import sys
from PIL import Image, ImageDraw, ImageFont
FONTS = [
    # name, path, pixel size
    ("font_small", "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf", 10),
    ("font_ui",    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 12),
    ("font_bold",  "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 12),
    ("font_big",   "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 16),
    ("font_read",  "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf", 14),
    ("font_readb", "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf", 14),
]
CHARS = [chr(c) for c in range(32, 127)] + ["•"]  # index 95 = bullet

def build(name, path, size):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs, data = [], bytearray()
    for ch in CHARS:
        l, t, r, b = f.getbbox(ch)
        adv = int(round(f.getlength(ch)))
        w = max(0, r - l)
        img = Image.new("L", (max(w, 1), h), 0)
        ImageDraw.Draw(img).text((-l, 0), ch, font=f, fill=255)
        px = img.load()
        off = len(data)
        nib = []
        for y in range(h):
            for x in range(w):
                nib.append(px[x, y] >> 4)
        if len(nib) % 2: nib.append(0)
        for i in range(0, len(nib), 2):
            data.append(nib[i] | (nib[i + 1] << 4))
        glyphs.append((off, w, adv, l))
    out = [f"static const unsigned char {name}_data[] = {{"]
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const u3_glyph {name}_glyphs[{len(CHARS)}] = {{")
    for off, w, adv, l in glyphs:
        out.append(f"  {{{off},{w},{adv},{l}}},")
    out.append("};")
    out.append(f"const u3_font {name} = {{ {name}_data, {name}_glyphs, {h}, {asc} }};")
    return "\n".join(out)

with open(sys.argv[1], "w") as fo:
    fo.write("/* Generated by tools/mkfont.py from DejaVu fonts (Bitstream Vera license). */\n")
    fo.write('#include "u3_gfx.h"\n\n')
    for n, p, s in FONTS:
        fo.write(build(n, p, s) + "\n\n")
